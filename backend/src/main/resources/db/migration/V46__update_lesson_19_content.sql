## 4. Контракты REST API для управления доской

Спроектируем лаконичный и понятный REST API:

- `GET /api/v1/crm/boards/{id}` — загрузка структуры доски (колонки и вложенные карточки, отсортированные по полю `position`).
- `POST /api/v1/crm/cards` — создание новой карточки в колонке "Новая заявка".
- `PATCH /api/v1/crm/cards/{id}/move` — атомарная операция перемещения карточки:
  ```json
  {
    "targetColumnId": 3,
    "newPosition": 0
  }
  ```
- `PUT /api/v1/crm/cards/{id}` — обновление названия, суммы сделки или приоритета.
- `DELETE /api/v1/crm/cards/{id}` — удаление карточки в корзину.

> [!NOTE]
> Обрати внимание: для перемещения карточки мы используем метод `PATCH`, а не `PUT`. Метод `PATCH` предназначен для частичного изменения ресурса (мы меняем только колонку и индекс позиции, не перезаписывая весь объект целиком).


## 1. Зачем бизнесу Kanban и почему все любят доски задач

Методология Kanban зародилась на заводах Toyota в 1950-х годах для контроля конвейерного производства, а сегодня стала стандартом во всех IT-гигантах (Jira, Trello, Linear, Asana).

В чём её сила?
Человеческий мозг визуален. Когда задачи записаны списком в блокноте, невозможно понять:
- На каком этапе процесс буксует (узкое горлышко)?
- Сколько сделок прямо сейчас находится на стадии переговоров?
- Кто из сотрудников перегружен, а кто простаивает?

В Kanban-доске всё на виду:
Колонки отображают стадии воронки: `Новая заявка (LEAD)` -> `Коммерческое предложение (PROPOSAL)` -> `Переговоры (NEGOTIATION)` -> `Оплата получена (WON)` / `Отказ (LOST)`.
Карточки физически перемещаются слева направо по мере продвижения сделки.


## 3. Четыре главных инженерных вызова недели

На этой неделе мы изучим технологии высшего уровня сложности:
1. **Streaming SSE (Server-Sent Events)**: Генерация ответа нейросети в реальном времени с задержкой первого токена менее 200мс.
2. **Векторный поиск pgvector**: Превращение заметок в многомерные векторы смыслов и семантический поиск похожих документов за 3мс прямо средствами SQL.
3. **RAG-система (Retrieval-Augmented Generation)**: Подмешивание найденного контекста в системный промпт модели с гарантией достоверности ответа.
4. **Безопасность и PII-маскирование**: Защита персональных данных от утечки во внешние нейросети (удаление номеров карт, паролей и личных контактов до отправки промпта).


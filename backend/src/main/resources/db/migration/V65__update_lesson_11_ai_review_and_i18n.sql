## 2. Шаг 1: AI-Промпт для внедрения мультиязычности i18n (RU / KZ / EN)

Мы не будем подключать тяжелые сторонние библиотеки для перевода. Мы создадим компактное, молниеносное решение на базе Zustand.

Отправь этот промпт в AI-чат:

```markdown
Ты — Frontend Lead. Добавь систему локализации и мультиязычности (i18n) для нашего Маркетплейса с поддержкой трёх языков: русский (RU), казахский (KZ) и английский (EN).

Выполни следующие задачи:

1. Создай словарь переводов: `src/shared/config/i18n/translations.ts`
   - Переведи все ключевые фразы интерфейса на 3 языка:
     * Навигация: Каталог / Каталог / Catalog, Корзина / Себет / Cart
     * Роли: Покупатель / Сатып алушы / Buyer, Продавец / Сатушы / Seller
     * Кнопки: Добавить в корзину / Себетке қосу / Add to Cart, Оформить заказ / Тапсырыс беру / Checkout, + Товар / + Тауар / + Product
     * Темы: Тёмная / Күңгірт / Dark, Светлая / Ашық / Light
     * Статусы: В наличии / Қоймада бар / In Stock, Итого / Барлығы / Total

2. Создай хранилище языка: `src/shared/model/languageStore.ts`
   - Тип: `Language = ''ru'' | ''kz'' | ''en''`.
   - Состояние: `lang` (по умолчанию ''ru'').
   - Действие: `setLanguage(lang)`.
   - Сохраняй выбор в LocalStorage через `persist` (ключ `marketplace-lang`).
   - Функция-хелпер `useTranslation()` (или хук `t()`), которая возвращает словарь для активного языка.

3. Обнови `src/widgets/header/ui/Header.tsx`:
   - Добавь аккуратный переключатель языка (RU | KZ | EN) в виде минималистичного селектора или кнопок.
```


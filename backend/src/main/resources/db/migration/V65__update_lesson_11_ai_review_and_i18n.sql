## 3. Шаг 2: AI-Промпт для глубокого архитектурного аудита (Code Review)

Теперь заставим AI провести беспощадный аудит кодовой базы нашего проекта.

Отправь в AI следующий мастер-промпт:

```markdown
Ты — Senior Tech Lead и главный архитектор проекта. Проведи строгий Code Review всего репозитория маркетплейса на React 19 + TypeScript + FSD.

Проверь код по 4 строгим критериям:

1. ИЗОЛЯЦИЯ СЛОЁВ FSD:
   - Нет ли запрещенных кросс-импортов между фичами (`features/cart` <-> `features/user`)?
   - Все ли сущности и фичи экспортируются ТОЛЬКО через публичные шлюзы `index.ts`?
   - Нет ли импортов снизу-вверх?

2. ЧИСТОТА TYPESCRIPT:
   - Найди и устрани любые типы `any` или небезопасные приведения `as unknown`.
   - Проверь типизацию всех пропсов компонентов и состояний хранилищ.

3. ДИЗАЙН-СИСТЕМА (СТРОГИЙ МОНОХРОМ):
   - Проверь, чтобы не было никаких случайных ярких цветов (зеленый, синий, желтый).
   - Вся палитра должна быть строго монохромной: #0a0a0c, #141418, border-white/10, text-white, text-zinc-400.

4. ПРОИЗВОДИТЕЛЬНОСТЬ И КЭШ:
   - Проверь селекторы Zustand в компонентах: компоненты должны подписываться только на нужные поля (`state => state.items`), а не на весь стор целиком.

Выдай список найденных замечаний и сразу примени точечный рефакторинг в файлах!
```


## 1. Проблема спагетти-кода и почему старые подходы умерли

Вспомни, как обычно учат организовывать проекты в интернете:
Создай папку `components/` и складывай туда все кнопки, шапки, модалки и карточки. Рядом создай папку `utils/` для всех функций, а рядом `services/` для всех запросов.

Пока в твоем проекте 5 компонентов — всё кажется простым.
Но представь, что проект вырос до 50 компонентов:
- В папке `components/` лежит 60 файлов вперемешку: `Button.tsx`, `Header.tsx`, `CartItem.tsx`, `UserAvatar.tsx`, `CheckoutModal.tsx`...
- Ты хочешь изменить цвет кнопки в корзине, меняешь файл — и внезапно ломается авторизация на странице профиля.
- Ты просишь AI добавить фильтр товаров, а он путается, потому что не понимает, какие компоненты зависят от каких.

Это называется **спагетти-код**: всё связано со всем, тронешь одну макаронину — дёргается вся тарелка.

> [!NOTE]
> Архитектура нужна не для того, чтобы усложнить жизнь. Архитектура нужна для того, чтобы через полгода ты или AI могли открыть проект, за 10 секунд понять, где лежит нужная логика, и внести изменения, ничего не сломав.

## 2. Иерархия слоёв FSD: как устроен порядок

Методология Feature-Sliced Design делит всё твоё приложение на 6 стандартизированных уровней (слоёв). Слои расположены строго сверху вниз:

```
┌────────────────────────────────────────┐
│ 1. app      (Инициализация, роутинг)   │
├────────────────────────────────────────┤
│ 2. pages    (Готовые страницы сайта)   │
├────────────────────────────────────────┤
│ 3. widgets  (Крупные блоки интерфейса) │
├────────────────────────────────────────┤
│ 4. features (Действия пользователя)    │
├────────────────────────────────────────┤
│ 5. entities (Бизнес-сущности: Товар)   │
├────────────────────────────────────────┤
│ 6. shared   (Универсальный фундамент)  │
└────────────────────────────────────────┘
```

Давай разберём каждый слой простыми словами на примере нашего Маркетплейса:

1. **shared**: Фундамент. Здесь лежит то, что не привязано к конкретному бизнесу. Базовые кнопки (`Button`), спиннеры загрузки, вспомогательные функции форматирования дат и цен, базовые настройки API клиентов.
2. **entities (Сущности)**: Главные герои твоего бизнеса. В маркетплейсе это: `Product` (карточка товара), `User` (пользователь и его роль), `Order` (заказ). Сущность знает, как отобразить себя и какие у неё есть поля, но она не знает, что с ней будут делать.
3. **features (Фичи / Действия)**: То, что приносит ценность пользователю. Например: `add-to-cart` (добавить в корзину), `filter-by-category` (отфильтровать каталог), `change-user-role` (переключить режим покупатель/продавец).
4. **widgets (Виджеты)**: Крупные самодостаточные блоки экрана, собранные из сущностей и фич. Например: `Header` (логотип + поиск + корзина), `ProductGrid` (каталог карточек с кнопками добавления), `CartDrawer` (выезжающая панель корзины).
5. **pages (Страницы)**: Полноценные экраны, привязанные к ссылкам: `CatalogPage` (главная), `ProductDetailPage` (страница конкретного товара), `SellerDashboardPage` (панель продавца). Страница — это просто композиция из нескольких виджетов.
6. **app (Приложение)**: Точка старта. Настройка роутера, глобальные стили, провайдеры контекста и конфигурация темы.

## 3. Главное правило FSD: закон однонаправленного потока

Запомни одно правило, которое спасёт тебя от 99% архитектурных ошибок:

> [!IMPORTANT]
> **Правило зависимостей FSD**: Модуль может импортировать код ТОЛЬКО из слоёв, которые расположены СТРОГО НИЖЕ него. Модули на одном и том же слое НЕ ИМЕЮТ ПРАВА импортировать друг друга напрямую.

Это значит:
- Виджет (`widgets`) может использовать фичу (`features`) и сущность (`entities`).
- Сущность (`entities`) **НЕ МОЖЕТ** импортировать фичу или виджет!
- Фича `add-to-cart` **НЕ МОЖЕТ** напрямую лезть в фичу `user-auth`.

Если двум модулям одного уровня нужны общие данные — эти данные либо спускаются на уровень ниже (в `entities` или `shared`), либо поднимаются на уровень выше (в `widgets`).

## 4. Публичный интерфейс: магия файла index.ts

Каждый срез (папка внутри слоя) защищает свои внутренности через **Public API** (файл `index.ts`).

Посмотри на структуру папки товара:
```
src/entities/product/
├── model/           # Приватные типы и логика (types.ts)
├── ui/              # Приватный React-компонент (ProductCard.tsx)
├── api/             # Приватные запросы к серверу (productApi.ts)
└── index.ts         # ПУБЛИЧНЫЙ ШЛЮЗ (Public API)
```

В файле `index.ts` мы явно объявляем, что мы разрешаем использовать остальному приложению:

```typescript
// Экспортируем наружу только необходимое:
export { ProductCard } from ''./ui/ProductCard'';
export type { Product } from ''./model/types'';
```

Всё остальное остаётся скрытым внутри. Внешний мир импортирует товар коротко и красиво:
```typescript
import { ProductCard, Product } from ''@/entities/product'';
```

Если завтра ты решишь переписать внутренности `ProductCard.tsx` — ни один другой файл в проекте не сломается, потому что публичный контракт остался неизменным.


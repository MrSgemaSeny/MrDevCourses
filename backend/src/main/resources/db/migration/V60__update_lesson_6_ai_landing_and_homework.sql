## 4. Публикация и деплой на GitHub Pages

Когда лендинг готов и проверен локально, опубликуй его в глобальном интернете:

1. Зафиксируй готовый результат в системе контроля версий:
   ```bash
   git add .
   git commit -m "feat: launch responsive ai-generated mvp landing with whatsapp checkout"
   git push origin main
   ```
2. Открой свой репозиторий на GitHub -> **Settings** -> **Pages**.
3. Убедись, что источник сборки настроен на ветку `main` и папку `/(root)`.
4. Через 1-2 минуты твой сайт станет доступен по адресу:
   `https://<твой-логин>.github.io/<имя-репозитория>/`

Открой эту ссылку на своём смартфоне — перед тобой живой работающий продукт, созданный тобой в связке с искусственным интеллектом.


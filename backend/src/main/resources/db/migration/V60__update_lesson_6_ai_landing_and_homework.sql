## 3. Протокол приёмки и ревью работы AI

Когда AI сгенерирует код и сохранит его в `index.html`, твоя инженерная обязанность — провести приёмочное тестирование (UAT — User Acceptance Testing):

1. **Проверка монохромности**:
   - Убедись, что на странице нет ядовитых градиентов, неоновых кнопок и разнобоя шрифтов.
2. **Мобильный аудит в DevTools (F12)**:
   - Переключи браузер в режим эмуляции смартфона (375px).
   - Проверь: сетка каталога перестраивается в 1 колонку, кнопки легко нажимаются пальцем, текст не выходит за границы экрана.
3. **Проверка интерактивного флоу**:
   - Нажми кнопку "Заказать" на любой карточке товара.
   - Проверь: открывается ссылка `wa.me` с корректным текстом сообщения, названием напитка и суммой.

> [!TIP]
> Если в ответе нейросети есть шероховатости (например, слишком мелкий шрифт цены или лишний отступ), не переписывай код руками. Отправь точечный промпт: *"Увеличь размер цены в карточках до text-xl font-mono text-white и добавь hover:border-white/40"*. Пусть AI работает на тебя.


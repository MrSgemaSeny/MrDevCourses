## 2. Мастер-промптинг: как заставить AI собрать лендинг целиком

Чтобы нейросеть автоматически сгенерировала готовый монохромный `index.html` без багов, передай ей контекст проекта в одном структурированном мастер-промпте.

Открой свой AI-ассистент (Cursor, Antigravity, Claude Code или веб-интерфейс Claude/ChatGPT) и отправь запрос:

```markdown
Ты — Senior Frontend Engineer и UI/UX дизайнер.
Твоя задача — сгенерировать целиком файл `index.html` для продающего MVP-лендинга кофейни CoffeeVibe.

Строго соблюдай инженерные стандарты из нашего `.agents/AGENTS.md`:
1. ТЕХНИЧЕСКИЙ СТЕК:
   - Семантический HTML5 (<header>, <main>, <section>, <footer>).
   - Tailwind CSS v4 через официальный CDN.
   - Мобильная адаптивность (Mobile First, идеальный вид на 375px и 4K).
   - Vanilla JavaScript для интерактивности без сторонних библиотек.

2. ДИЗАЙН-СИСТЕМА (ТОЛЬКО ЧЕРНО-БЕЛАЯ ПАЛИТРА):
   - Фон страницы: #0a0a0c.
   - Фон карточек: #141418, границы border border-white/10, hover:border-zinc-500.
   - Текст: основной text-white, вторичный text-zinc-400.
   - Главные кнопки CTA: bg-white text-black font-semibold hover:bg-zinc-200.
   - Никаких случайных цветов (синих, зеленых, желтых градиентов).

3. СТРУКТУРА СЕКЦИЙ:
   - Header: логотип CoffeeVibe, ссылки "Меню", "О нас", кнопка "Предзаказ".
   - Hero: бейдж "Сезонное меню • Без очередей", цепляющий заголовок H1, оффер и крупная кнопка CTA с якорным скроллом к меню.
   - Меню (Каталог): сетка из 4 карточек (Капучино, Фильтр-кофе, Раф, Матча) с ценами в тенге (₸) и кнопками "Заказать".
   - Доверие: 3 компактных преимущества (готовность за 3 минуты, свежая обжарка, упаковка с собой).
   - Интерактивная логика: функция sendOrder(name, price), которая открывает диалог в WhatsApp с предзаполненным заказом по клику на кнопку.
   - Footer: адрес, режим работы, копирайт.

Выдай только готовый рабочий код index.html целиком без пропусков и сокращений.
```


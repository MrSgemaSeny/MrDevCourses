## 1. Смена парадигмы: от кодера к дирижёру AI

В классической разработке 80% времени уходит на рутинный набор тегов, выравнивание flexbox-контейнеров и поиск опечаток в классах стилей.

В парадигме вайбкодинга твоя роль меняется:
- **Ты** — определяешь бизнес-цель, задаёшь архитектурные ограничения в `.agents/AGENTS.md` и проверяешь качество результата.
- **AI** — пишет чистую семантическую разметку, подключает Tailwind CSS, настраивает адаптивную сетку под смартфоны и собирает интерактивный скрипт отправки заявок.

> [!IMPORTANT]
> AI — это не замена инженера, а сверхмощный экзоскелет. Если дать ему размытую задачу без ограничений — он выдаст сломанный и визуально грязный сайт. Но если сопроводить его чётким ТЗ и дизайн-системой — он соберёт продающий лендинг за 5 минут.


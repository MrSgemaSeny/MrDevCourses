В этом уроке мы разберём самую востребованную и дорогую технологию в современном искусственном интеллекте — **RAG (Retrieval-Augmented Generation / Генерация с дополнением выборки)**. Мы поймём, почему языковые модели галлюцинируют, как научить нейросеть мгновенно ориентироваться в твоих личных данных без миллионных бюджетов на обучение и подключим векторное расширение `pgvector` прямо внутри PostgreSQL.

## 1. Проблема галлюцинаций LLM и почему дообучение (Fine-Tuning) — тупик для 95% задач

Представь: ты спрашиваешь у ChatGPT или Claude:
*"Сколько денег я потратил на покупку авиабилетов в прошлый вторник и какой статус у сделки с клиентом Азаматом?"*

Что ответит модель?
Она либо скажет: *"У меня нет доступа к вашим личным данным"*, либо (что ещё хуже) уверенно придумает случайную цифру и статус. Это называется **галлюцинацией**. Модель обучалась на открытом интернете до определенной даты и ничего не знает о твоей жизни.

Что пытались делать раньше?
Думали: *"Давайте дообучим (Fine-Tune) модель на наших личных документах!"*.
Но на практике это превратилось в катастрофу:
- Обучение стоит тысячи долларов и занимает дни.
- Если ты добавишь новую заметку через минуту — модель нужно обучать заново!
- Модель всё равно может перепутать цифры или забыть старую информацию (Catastrophic Forgetting).

> [!NOTE]
> **RAG (Retrieval-Augmented Generation)** решает эту проблему гениально просто: мы НЕ обучаем модель заново. Мы храним данные в быстрой векторной базе, находим нужные фрагменты за 5 миллисекунд и подсовываем их модели в контекст вопроса прямо перед ответом.

## 2. Что такое векторные эмбеддинги: геометрия смысла на пальцах

Компьютер не понимает человеческих слов. Для него слово "кофе" — это просто набор байтов. Но математики придумали способ превращать смысл текста в набор чисел — **Embedding (Векторное представление)**.

Модель эмбеддингов (например, `text-embedding-3-small` от OpenAI) берет предложение и возвращает массив из 1536 чисел с плавающей точкой:
`[0.0124, -0.0452, 0.8912, ...]`

Удивительное свойство этих чисел:
- Предложения, близкие по смыслу, получают близкие координаты в 1536-мерном пространстве.
- Фразы *"Я заплатил за латте"* и *"Расход на чашку капучино"* будут находиться почти в одной точке пространства.
- А фраза *"Установка драйвера на видеокарту"* окажется очень далеко.

Измерить схожесть двух текстов теперь можно простой школьной формулой геометрии — **косинусным расстоянием между двумя стрелками векторов**.

## 3. Расширение pgvector в PostgreSQL: векторная база без лишних костылей

Раньше для хранения векторов приходилось поднимать отдельные базы данных (Pinecone, Qdrant, Milvus). Это усложняло архитектуру в 3 раза.

Сегодня в любимом PostgreSQL есть официальное расширение **pgvector**, которое позволяет хранить векторы прямо в колонке таблицы и искать по ним со скоростью света.

Создадим Flyway-миграцию:

```sql
-- 1. Включаем векторное расширение в PostgreSQL
CREATE EXTENSION IF NOT EXISTS vector;

-- 2. Таблица семантических представлений документов
CREATE TABLE document_embeddings (
    id BIGSERIAL PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    document_type VARCHAR(50) NOT NULL, -- ''NOTE'', ''CRM_CARD'', ''TRANSACTION''
    source_id BIGINT,                    -- Ссылка на ID оригинальной сущности
    content TEXT NOT NULL,               -- Исходный фрагмент текста
    embedding vector(1536),              -- 1536-мерный вектор смысла
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 3. HNSW Индекс (Hierarchical Navigable Small World) для мгновенного приближенного поиска
CREATE INDEX idx_document_embeddings_hnsw 
ON document_embeddings 
USING hnsw (embedding vector_cosine_ops);
```

## 4. Пайплайн RAG в реальном времени: шаг за шагом

Когда пользователь отправляет вопрос в чат Pensee:
1. **Шаг 1 (Векторизация вопроса)**: Бэкенд отправляет текст вопроса в Embedding API и получает вектор `Q` (1536 чисел).
2. **Шаг 2 (Поиск в PostgreSQL)**: Бэкенд выполняет один SQL-запрос с оператором косинусного расстояния `<=>`:
   ```sql
   SELECT id, document_type, content, (1 - (embedding <=> :queryVector)) AS similarity
   FROM document_embeddings
   WHERE user_id = :currentUserId
   ORDER BY embedding <=> :queryVector ASC
   LIMIT 3;
   ```
   PostgreSQL за 4 миллисекунды находит 3 самых релевантных заметки.
3. **Шаг 3 (Сборка расширенного промпта)**: Бэкенд склеивает найденный контекст с системным промптом:
   ```
   Ты — AI советник Pensee. Отвечай на вопрос строго на основе предоставленного контекста!
   
   --- НАЙДЕННЫЙ КОНТЕКСТ ИЗ БАЗЫ ДАННЫХ ---
   1. Сделка CRM: "Разработка сайта для кофейни", сумма 350 000 ₸, статус: WON (Оплачено).
   2. Финансы: Расход 45 000 ₸ по счету Kaspi Gold (категория: Оборудование).
   -----------------------------------------
   
   Вопрос пользователя: Сколько денег принесла сделка с кофейней?
   ```
4. **Шаг 4 (Генерация ответа)**: Модель Claude читает контекст и даёт стопроцентно точный, достоверный ответ:
   *«Сделка ''Разработка сайта для кофейни'' успешно закрыта и принесла 350 000 ₸.»*

Никаких галлюцинаций. Чистая математика и факты.


## 1. Что мы построили: архитектурный смотр проекта

Давай оглянемся на то, что уже работает в твоём приложении:

```
1. Архитектура Feature-Sliced Design (FSD)
   - app/: глобальные провайдеры, роутер, стили Tailwind CSS.
   - pages/: главная страница каталога с фильтрами, переключателями и корзиной.
   - widgets/: шапка (Header) с переключателями ролей, тем, языков и кнопкой корзины.
   - features/: добавление в корзину (add-to-cart), переключение тем (theme-toggle), мультиязычность (language-selector), создание товара продавцом.
   - entities/: сущность товара (ProductCard, productStore) и корзины (CartDrawer, cartStore).
   - shared/: переиспользуемые UI-компоненты (Button, Drawer, Modal), конфиг i18n и типы.

2. Ключевые возможности:
   - Ролевая модель: Покупатель (каталог, корзина) / Продавец (создание товаров на лету).
   - Dark / Light Mode: монохромная темная и чистая светлая темы через класс dark.
   - Мультиязычность (i18n): мгновенное переключение RU / KZ / EN для всех элементов UI.

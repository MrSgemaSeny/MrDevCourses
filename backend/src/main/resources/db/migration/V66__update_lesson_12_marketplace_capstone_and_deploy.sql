## 3. Шаг 2: Настройка CI/CD пайплайна (GitHub Actions)

В индустрии никто не деплоит сайты вручную через перетаскивание файлов. Мы настраиваем автоматический робот (GitHub Actions), который при каждом твоем коммите в ветку `main` сам соберет проект, проверит типы и выложит свежую версию на GitHub Pages.

Отправь этот промпт в AI-чат:

```markdown
Создай файл GitHub Actions workflow для автоматического деплоя нашего React Vite приложения на GitHub Pages.

Путь к файлу: `.github/workflows/deploy.yml`

Требования к workflow:
1. Запуск: при каждом push в ветку `main` и вручную (workflow_dispatch).
2. Права (permissions): `contents: read`, `pages: write`, `id-token: write`.
3. Окружение: `ubuntu-latest`, Node.js 20.
4. Шаги:
   - Checkout репозитория (`actions/checkout@v4`).
   - Настройка Node.js (`actions/setup-node@v4`) с кэшированием npm.
   - Установка зависимостей (`npm ci` или `npm install`).
   - Сборка production-бандла (`npm run build`).
   - Загрузка артефакта Pages (`actions/upload-pages-artifact@v3` с path: `./dist`).
   - Деплой на GitHub Pages (`actions/deploy-pages@v4`).

Предоставь готовый файл YAML и объясни, какие настройки нужно включить в репозитории на GitHub.
```

### Настройка репозитория на GitHub:
```
1. Зайди в свой репозиторий на GitHub.
2. Перейди во вкладку: Settings -> Pages.
3. В разделе "Build and deployment" -> "Source" выбери: "GitHub Actions".
4. Сохрани настройки.
5. Сделай git push в ветку main — во вкладке "Actions" начнется автоматическая сборка.
6. Через 1-2 минуты появится зеленая галочка и ссылка на твой живой сайт:
   https://<твой-логин>.github.io/<имя-репозитория>/
```


Выполни следующие шаги:
1. Проверь конфигурацию `vite.config.ts`:
   - Убедись, что параметр `base` настроен на относительный путь или переменную окружения: `base: ''./''` (или `base: process.env.VITE_BASE_PATH || ''/''`).
2. Проверь роутер `src/app/router.tsx` (если используется BrowserRouter или HashRouter):
   - Для стабильной работы на GitHub Pages без серверной переадресации используй HashRouter либо настрой SPA 404 fallback скрипт.
3. Проверь команду сборки в `package.json`:
   - `"build": "tsc -b && vite build"`.
4. Сгенерируй скрипт для копирования `index.html` в `dist/404.html` после сборки, чтобы при прямом переходе по ссылкам GitHub Pages не выдавал 404 Not Found:

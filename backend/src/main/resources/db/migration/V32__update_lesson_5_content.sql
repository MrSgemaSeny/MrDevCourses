## 2. Формула Customer Problem Statement: как сформулировать боль в одном предложении

Прежде чем написать хотя бы одну строчку HTML или просить AI сгенерировать страницу, заполни строгую инженерную формулу:

> **[Конкретная группа людей]** сталкивается с **[Конкретное неудобство / Боль]**, когда пытается **[Какое действие они совершают]**, из-за чего **[К какому плохому результату это приводит: потеря денег, времени, нервов]**.

Сравним слабую и сильную формулировку:

- **Слабо**: "Я хочу сделать сайт для кофейни, чтобы там было красивое меню." (Здесь нет проблемы, просто желание сделать дизайн).
- **Сильно**: "Офисные сотрудники в бизнес-центрах тратят от 15 до 20 минут в утренней очереди за кофе, из-за чего опаздывают на планёрки и часто отказываются от покупки."

Чувствуешь разницу? Во втором случае сразу понятно, что делать: нужен не просто "красивый сайт с историей кофейных зерен", а быстрый инструмент предзаказа с выбором времени самовывоза, где заказ оформляется за 3 клика со смартфона.

## 3. Целевая аудитория: кто твой первый пользователь

Частая ошибка — говорить: "Мой сайт нужен всем!". Всем — значит никому.

На этапе первой недели выбери одного конкретного человека, для которого ты строишь решение:
- Это студент, которому нужно быстро найти репетитора по математике?
- Это мастер маникюра, которая устала вручную переписываться с клиентами в Direct Instagram и путает записи?
- Это локальная пекарня, которая теряет заказы на торты в WhatsApp?

Опиши его в 3 предложениях:
1. Какой у него распорядок дня и в какой момент возникает проблема?
2. Каким устройством он пользуется чаще всего (95% вероятность, что это смартфон на бегу)?
3. Что он делает прямо сейчас, чтобы решить эту проблему (например, пишет в блокнотик или звонит по телефону)?

## 4. Безжалостный скоупинг (Feature Scope): метод MoSCoW

Когда в голову приходит идея, хочется реализовать 50 функций сразу. Чтобы не утонуть в деталях, профессиональные продуктовые менеджеры используют приём **MoSCoW**:

1. **Must Have (Критически обязательно)**: Без этого продукт вообще не решает заявленную проблему. Для нашей кофейни: список из 5 напитков с ценами, выбор времени, кнопка отправки заказа.
2. **Should Have (Важно, но не блокирует запуск)**: Поиск по каталогу, выбор объёма стаканчика (250мл / 400мл). Сделаем во второй версии.
3. **Could Have (Приятные мелочи)**: Тёмная и светлая тема, система накопительных баллов, промокоды на скидку. Откладываем.
4. **Won''t Have (Категорически запрещено делать в MVP)**: Авторизация через Госуслуги, онлайн-эквайринг с чеками, интеграция со складом и мобильное приложение в App Store.

> [!WARNING]
> Главная причина срыва дедлайнов — creeping scope (расползание рамок проекта). Как только во время разработки у тебя возникает мысль: "А давай ещё прикрутим вот эту маленькую фичу", бей себя по рукам и записывай её в отдельный список "Версия 2.0".

## 5. Формулируем User Stories (Пользовательские истории)

User Story — это стандартный способ описания требований к коду от лица человека:

> *Как [тип пользователя], я хочу [какое действие совершить], чтобы [какую пользу получить].*

Примеры для нашего лендинга:
- *Как спешащий офисный работник, я хочу увидеть меню и цены сразу на первом экране без бесконечной прокрутки, чтобы мгновенно определиться с выбором.*
- *Как клиент, я хочу выбрать напиток и нажать одну кнопку, чтобы в WhatsApp открылся готовый текст заказа, и мне не пришлось вбивать названия пальцами.*


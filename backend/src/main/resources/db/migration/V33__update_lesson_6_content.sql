## 3. Интерактивная логика: отправка заказа в WhatsApp без бэкенда

Для MVP первой недели нам не нужна сложная база данных и платежный шлюз. Мы сделаем элегантное инженерное решение: клиент нажимает кнопку, и браузер открывает WhatsApp с предзаполненным текстом заказа:

```javascript
// Функция отправки заказа в WhatsApp
function sendOrder(productName, price) {
  // Укажи номер телефона кофейни в международном формате (без знака плюс)
  const phoneNumber = "77001234567";
  
  // Формируем вежливый читаемый текст сообщения
  const rawMessage = "Здравствуйте! Хочу оформить предзаказ через сайт:\n" +
                     "- Напиток: " + productName + "\n" +
                     "- Стоимость: " + price + " ₸\n\n" +
                     "Подскажите, через сколько минут можно забрать?";
  
  // Кодируем текст для безопасной передачи в URL
  const encodedMessage = encodeURIComponent(rawMessage);
  
  // Открываем диалог в новой вкладке
  const whatsappUrl = "https://wa.me/" + phoneNumber + "?text=" + encodedMessage;
  window.open(whatsappUrl, "_blank");
}
```

Проверь сам: нажми на кнопку — и у тебя откроется WhatsApp с готовым текстом. Клиенту остаётся нажать одну кнопку "Отправить".


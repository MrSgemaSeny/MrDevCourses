## 1. Анатомия современного инженерного лендинга

Забудь о перегруженных сайтах из 2015 года с летающими баннерами, всплывающими окнами и десятками бессмысленных картинок. Современный веб ценит скорость, ясность и визуальный покой.

Лендинг уровня MVP состоит из 5 обязательных смысловых секций:

1. **Header (Шапка)**: Название проекта или логотип, 2-3 якорные ссылки на разделы и заметная кнопка действия.
2. **Hero Section (Главный экран)**: Самый важный блок. Здесь пользователь решает за 3 секунды, остаться на сайте или закрыть вкладку. Содержит ёмкий заголовок (Problem/Value), краткое пояснение и крупную кнопку призыва к действию (CTA — Call To Action).
3. **Features & Products (Каталог / Преимущества)**: Чёткая сетка карточек с предложениями, описанием, ценниками и кнопками выбора.
4. **Social Proof & Guarantees (Доверие)**: 2-3 коротких тезиса, снимающих страхи клиента (время приготовления 3 минуты, свежая обжарка зёрен, гарантия возврата).
5. **Footer (Подвал)**: Контакты, режим работы, ссылка на соцсети и копирайт.

> [!NOTE]
> В нашем курсе мы придерживаемся строгой монохромной инженерной эстетики: глубокий тёмный фон (`#0a0a0c`), аккуратные карточки (`#141418`) с тонкими рамками (`border-white/10`) и контрастный белый акцент для кнопок действия (`bg-white text-black`). Это выглядит дорого, современно и профессионально.

## 2. Пошаговая работа с AI: не проси всё сразу

Главная ошибка новичка в вайбкодинге — написать в чат: *"Напиши мне полностью готовый сайт для кофейни с меню и отправкой заказов"*.
Нейросеть выплюнет 800 строк случайного кода, половина функций не будет работать, а стили разъедутся на телефоне.

Профессиональный метод — **пошаговая итеративная сборка**:


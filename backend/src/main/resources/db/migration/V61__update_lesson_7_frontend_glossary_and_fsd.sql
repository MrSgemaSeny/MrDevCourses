## 5. React 19 — библиотека декларативного UI

React — это библиотека от Meta для построения интерфейсов из независимых компонентов.

**Главная идея React:** `UI = f(data)` (Интерфейс — это функция от данных).

Ты не пишешь императивные команды браузеру в духе *"найди блок с id=cart, посчитай сумму и замени текст"*. Ты декларативно описываешь, как экран должен выглядеть при том или ином состоянии данных. Когда данные меняются — React сам вычисляет разницу (Virtual DOM / Reconciliation) и точечно перерисовывает только нужный кусок страницы.

**Компонент** — это изолированный фрагмент интерфейса, оформленный как JavaScript-функция, возвращающая JSX (разметку). Кнопка, карточка товара, шапка сайта, модальное окно — всё это компоненты, которые собираются как детали конструктора.


## 3. Vite — молниеносный сборщик проекта

В современном веб-приложении у тебя десятки файлов `.tsx`, модули стилей, картинки и шрифты. Браузер не может эффективно загружать сотни разрозненных файлов по отдельности.

**Vite** берёт весь твой исходный код и:
1. Компилирует TypeScript в чистый JavaScript.
2. Объединяет модули в компактные бандлы (bundles).
3. Минифицирует код (удаляет пробелы, сокращает имена переменных для экономии трафика).
4. Запускает локальный dev-сервер с мгновенной заменой модулей при сохранении (Hot Module Replacement / HMR).

```bash
npm run dev    →  Vite запускает локальный сервер localhost:5173 и мгновенно обновляет экран
npm run build  →  Vite компилирует проект в папку dist/ — готово к деплою
```

Без сборщика вроде Vite тебе пришлось бы писать весь код в один гигантский HTML-файл на 5 000 строк.


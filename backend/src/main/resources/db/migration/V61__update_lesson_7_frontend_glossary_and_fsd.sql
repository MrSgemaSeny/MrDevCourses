## 7. DTO, Zod и Shared API: как фронтенд общается с бэкендом

Любое взрослое приложение взаимодействует с сервером по строгим правилам:

1. **DTO (Data Transfer Object)**:
   Форма и контракт данных, которыми обмениваются клиент и сервер. Бэкенд возвращает ровно то, что ожидает фронтенд. Если бэкенд переименует поле `price` в `cost`, TypeScript сразу подсветит ошибку во всех компонентах до деплоя.
2. **Zod (Рантайм-валидация)**:
   TypeScript защищает типы только во время написания кода. Но когда реальные данные приходят от пользователя из формы или из ответа сервера — TypeScript уже не работает. Zod валидирует реальные входящие данные в рантайме и отсекает мусор.
3. **Shared API Слой (`shared/api/`)**:
   Все сетевые HTTP-запросы изолируются в одном централизованном месте. Если завтра поменяется базовый URL сервера или способ передачи JWT-токена, правка вносится в один файл `apiClient.ts`, а не разыскивается по пятидесяти компонентам.


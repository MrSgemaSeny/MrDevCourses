## 1. JavaScript (JS) — основа всего

Единственный язык программирования, который нативно понимает браузер.

```
Браузер умеет читать три базовые вещи:
  HTML  →  структура (что есть на странице: кнопки, карточки, текст)
  CSS   →  внешний вид (как это выглядит: цвета, отступы, сетка)
  JS    →  поведение (что происходит при клике, отправка данных)
```

Когда ты нажимаешь кнопку и появляется всплывающее модальное окно — это JavaScript. Когда данные подгружаются с сервера без перезагрузки всей страницы — это тоже JavaScript.

**Главная проблема чистого JS:** он не проверяет типы данных до запуска. Если функция ожидает число, а ты случайно передал туда строку или `null`, ты узнаешь об ошибке только в продакшне, когда реальный пользователь нажмёт кнопку и увидит белый экран.


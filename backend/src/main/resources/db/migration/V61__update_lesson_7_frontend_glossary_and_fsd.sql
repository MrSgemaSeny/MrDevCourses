## 8. State Management: управление состоянием в React

**Состояние (State)** — это любые данные в приложении, изменение которых приводит к обновлению интерфейса.

В профессиональной разработке состояние строго делится на три уровня:

```
┌─────────────────────────┬───────────────────┬───────────────────────────────────────────┐
│ Тип состояния           │ Инструмент        │ Что именно там хранится                   │
├─────────────────────────┼───────────────────┼───────────────────────────────────────────┤
│ 1. Локальное (Local UI) │ useState, useRef  │ Открыта ли модалка, текст в поле поиска   │
│ 2. Серверное (Server)   │ React Query       │ Список товаров с бэкенда, кеш, загрузка   │
│ 3. Глобальное (Client)  │ Zustand           │ Корзина покупок, текущая роль (покупатель) │
└─────────────────────────┴───────────────────┴───────────────────────────────────────────┘
```

- **useState**: Хранит значение внутри одного компонента. Изменилось значение — компонент перерисовался.
- **useRef**: Хранит ссылку на DOM-элемент или значение между рендерами БЕЗ вызова перерисовки.
- **React Query**: Автоматически управляет серверными данными — показывает спиннеры загрузки, кеширует ответы, заново запрашивает данные при потере фокуса.
- **Zustand**: Глобальное клиентское хранилище. Любой компонент на любой глубине дерева может прочитать или изменить данные корзины напрямую без передачи пропсов через 10 промежуточных компонентов (избавление от Prop Drilling).


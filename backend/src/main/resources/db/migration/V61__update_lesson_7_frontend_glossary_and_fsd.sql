## 4. Landing vs SPA (Single Page Application)

Давай чётко зафиксируем разницу между сайтом, который мы делали на Неделе 1, и приложением, которое мы начинаем строить сейчас:

```
Лендинг (Landing Page) — это:       SPA (Single Page Application) — это:
──────────────────────────────       ─────────────────────────────────────────
Один статичный HTML-файл             Приложение, живущее в одном HTML
Несколько информационных секций      Множество экранов (/catalog, /cart, /admin)
Кнопка "заказать в WhatsApp"         Полноценная авторизация и роли (RBAC)
Нет личного кабинета                 Глобальное состояние (корзина, профиль)
Нет сложной логики данных            Мгновенные переходы без перезагрузки страницы
```

В **SPA (React-приложении)** браузер загружает `index.html` и бандл скриптов один раз при первом входе. Дальше React сам подменяет блоки на экране при переходе по ссылкам, а данные подгружаются в фоне через REST API без мигания страницы.


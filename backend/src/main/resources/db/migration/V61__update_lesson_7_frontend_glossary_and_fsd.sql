## 6. Tailwind CSS и Lucide Icons

- **Tailwind CSS**: Утилитарный CSS-фреймворк. Вместо написания громоздких `.css` файлов с придумыванием сотен названий классов, ты применяешь атомарные классы прямо в JSX (`bg-[#0a0a0c]`, `text-white`, `p-4`, `rounded-md`, `border border-white/10`).
- **Lucide React**: Библиотека чистых масштабируемых SVG-иконок в виде React-компонентов (`<ShoppingCart />`, `<Search />`, `<User />`). Иконки кастомизируются через пропсы (размер, цвет, толщина линии).


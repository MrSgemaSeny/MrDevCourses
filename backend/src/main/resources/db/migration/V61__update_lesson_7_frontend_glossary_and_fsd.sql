## 2. TypeScript (TS) — JS с памятью и проверкой типов

TypeScript — это JavaScript с надстроенной системой строгой статической типизации.

Ты явно описываешь, что именно ожидает каждая функция, переменная или компонент. Редактор кода (IDE) подчёркивает ошибки моментально ещё до запуска программы.

```
Твой код (.ts / .tsx)
        │
        ▼  компиляция (tsc / Vite делает это автоматически на лету)
        │
Обычный JS (.js)
        │
        ▼
   Браузер читает
```

> [!IMPORTANT]
> **Важно помнить:** Браузер не умеет выполнять TypeScript напрямую. Перед запуском TypeScript всегда компилируется (транспилируется) в чистый оптимизированный JavaScript. TypeScript — это инструмент инженера для защиты от багов во время разработки.


## 9. Feature-Sliced Design (FSD): архитектура проекта

Когда в проекте 5 компонентов — структура не имеет значения. Но когда маркетплейс вырастает до 50 компонентов, корзины, фильтрации, панели продавца и админки — проект без архитектуры превращается в нераспутываемый спагетти-монолит.

**Feature-Sliced Design (FSD)** — это стандарт структурирования фронтенда, разбивающий код на строгие слои ответственности:

```
src/
├── app/            # Инициализация приложения, глобальные провайдеры, роутер
├── pages/          # Страницы приложения (CatalogPage, ProductPage, DashboardPage)
├── widgets/        # Крупные самодостаточные блоки (Header, ProductGrid, CartDrawer)
├── features/       # Действия пользователя (add-to-cart, filter-products, switch-role)
├── entities/       # Бизнес-сущности (Product, User, Order)
└── shared/         # Универсальные компоненты (Button, Input, apiClient, utils)
```

### Главный закон FSD: Однонаправленный поток импортов
> [!WARNING]
> Модуль может импортировать код **ТОЛЬКО из слоёв, расположенных СТРОГО НИЖЕ него**. Модули одного слоя не имеют права импортировать друг друга напрямую.

- `pages` может использовать `widgets`, `features`, `entities`, `shared`.
- `widgets` может использовать `features`, `entities`, `shared`.
- `features` может использовать `entities`, `shared`.
- `entities` может использовать ТОЛЬКО `shared`.
- `shared` — независимый фундамент, ничего не импортирует из других слоёв.

### Публичный контракт: Public API (`index.ts`)
Каждая папка внутри слоя закрывает свои внутренности и открывает наружу только публичные элементы через `index.ts`:

```typescript
// src/entities/product/index.ts
export { ProductCard } from ''./ui/ProductCard'';
export type { Product } from ''./model/types'';
```


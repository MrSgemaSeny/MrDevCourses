В этом уроке мы разберём разницу между кодом новичка и кодом профессионального инженера. Мы поговорим не просто о папках и файлах, а о мышлении: почему 90% пет-проектов умирают на второй неделе, как структурировать проект так, чтобы в нём не путался ни ты, ни искусственный интеллект, и как составить файл инструкций для нейросети, который сэкономит тебе десятки часов.

## 1. Ловушка перфекционизма и почему MVP спасает проекты

Представь типичную историю: человек загорелся идеей сделать свой сервис. Допустим, онлайн-сервис заказа еды.

Что он делает?
Вместо того чтобы сделать простую страницу с тремя блюдами и кнопкой заказа в WhatsApp, он начинает планировать: "Так, мне нужна авторизация по отпечатку пальца, оплата Apple Pay, система бонусов, рекомендательная нейросеть, поддержка 10 языков и чат с курьером на карте в реальном времени".

Проходит месяц. Написана половина сложнейшей базы данных. Ничего не работает. Ни один реальный человек так и не увидел проект. У автора опускаются руки, проект отправляется на кладбище недоделанных идей.

> [!NOTE]
> **MVP (Minimum Viable Product — Минимально жизнеспособный продукт)** — это самая ранняя версия продукта, которая решает одну главную проблему одного конкретного пользователя с абсолютным минимумом функций.

Инженерное правило: если ты можешь выкинуть фичу и продукт всё ещё выполняет свою ключевую задачу — выкидывай её без раздумий. Сначала собери простой работающий скелет, покажи его людям, получи обратную связь — и только потом наращивай сложность.

## 2. Файловая архитектура: как не устроить свалку

Когда ты работаешь с AI-ассистентом, файловый порядок важен вдвойне. Если все файлы (картинки, стили, скрипты, разметка) свалены в одну кучу в корне проекта, нейросеть начинает путать контекст, предлагать дублирующие функции и ломать относительные пути.

Вот стандарт чистой структуры для фронтенд-проекта:

```
my-landing-project/
├── .agents/              # Инструкции и архитектурные ограничения для AI
│   └── AGENTS.md         # Свод правил для нейросетей
├── assets/               # Статические ресурсы
│   ├── images/           # Картинки, скриншоты, фото
│   └── icons/            # Иконки и векторные логотипы (SVG)
├── css/                  # Стили оформления
│   └── style.css         # Таблица стилей
├── js/                   # Скрипты клиентской логики
│   └── app.js            # Интерактивное поведение
├── .gitignore            # Список файлов, которые нельзя отправлять в Git
├── index.html            # Главная точка входа для браузера
└── README.md             # Главный документ проекта: лицо твоей работы
```

Каждая папка отвечает строго за своё назначение. Ты всегда знаешь, где искать картинку, а AI всегда знает, куда положить новый скрипт.

## 3. Золотой стандарт README.md: визитная карточка инженера

Файл `README.md` (написанный на языке разметки Markdown) — это первое, что видит любой человек, открывающий твой репозиторий на GitHub. По качеству README работодатели и коллеги за 10 секунд определяют, кто перед ними: хаотичный любитель или системный разработчик.

Хороший README содержит 5 обязательных блоков:
1. **Заголовок и однострочный оффер**: Что это за проект и какую задачу он решает.
2. **Живое демо**: Прямая кликабельная ссылка на задеплоенный сайт на GitHub Pages.
3. **Стек технологий**: Перечисление инструментов с понятным разделением.
4. **Ключевые возможности (Features)**: Короткий маркированный список того, что работает прямо сейчас.
5. **Инструкция по локальному запуску**: 2-3 терминальные команды, чтобы любой мог запустить проект на своём компьютере.

Пример эталонного README:

```markdown
# CoffeeVibe — Минималистичный лендинг авторской кофейни

Адаптивный тёмный лендинг для локальной кофейни с интерактивным каталогом напитков и мгновенным оформлением заказа через WhatsApp.

## Живое демо
[Открыть сайт на GitHub Pages](https://username.github.io/coffee-vibe/)

## Технологический стек
- HTML5 семантическая разметка (Mobile First)
- Tailwind CSS v4 (строгая тёмная монохромная эстетика)
- Vanilla JavaScript (LocalStorage для сохранения корзины)
- GitHub Pages & Actions (автоматический деплой)

## Возможности
- Адаптивная вёрстка под экраны от 360px до 4K
- Каталог напитков с ценами и составом
- Интерактивный калькулятор стоимости заказа
- Формирование предзаполненного сообщения в мессенджер

## Быстрый старт
1. Склонируйте репозиторий:
   git clone https://github.com/username/coffee-vibe.git
2. Откройте \`index.html\` в любом браузере.
```

## 4. Файл инструкций для AI: .agents/AGENTS.md

В 2024–2026 году разработка неразрывно связана с AI. Но если не давать нейросети чётких рамок, она начнёт генерировать код так, как ей вздумается: вставит случайные цвета, подключит пять тяжёлых библиотек или напишет код на устаревшем стандарте десятилетней давности.

Чтобы обуздать AI, в корне проекта создаётся папка `.agents/` и файл `AGENTS.md`. Это конституция твоего проекта. Редакторы вроде Cursor, Antigravity или Claude Code читают этот файл перед каждым ответом.

Создадим `.agents/AGENTS.md`:

```markdown
# Инструкции для AI-ассистентов в проекте CoffeeVibe

## Общие правила
- Всегда объясняй архитектурные решения: сначала пиши, ПОЧЕМУ ты делаешь изменение, затем показывай код.
- Общайся на русском языке. Будь лаконичным, без лишней вежливости и воды.
- Никаких эмодзи в коде, комментариях или коммитах.

## Стандарты вёрстки и дизайна
- Семантический HTML5: обязательно используй теги <header>, <main>, <section>, <article>, <footer>.
- Дизайн-система: строгая тёмная монохромная палитра (#0a0a0c фон страницы, #141418 карточки, border-white/10 рамки, белый текст #ffffff, приглушённый #a1a1aa).
- Запрещено использовать яркие случайные цвета (синий, оранжевый, зелёный), кроме необходимых служебных индикаторов.
- Подход Mobile First: сайт обязан безупречно открываться на экранах смартфонов шириной 375px.

## Чистота кода
- Не подключай внешние JS-библиотеки без прямого разрешения.
- Все функции должны иметь понятные названия на английском (camelCase).
- Всегда добавляй проверку на существование DOM-элементов перед добавлением event listener.
```

> [!TIP]
> Когда ставишь задачу в чате с AI, всегда добавляй фразу: *"Следуй правилам из `.agents/AGENTS.md`"*. Это сокращает количество галлюцинаций нейросети на 80%.

## 5. Как декомпозировать задачи с помощью AI

Когда перед тобой стоит большая задача (например, "сделать форму заказа"), не проси AI сделать всё за один промпт. Разбей работу на микро-шаги:
1. Шаг 1: Разметка полей формы (имя, телефон, адрес) в HTML.
2. Шаг 2: Стилизация под тёмную тему в Tailwind CSS.
3. Шаг 3: Валидация введённого номера телефона в JavaScript.
4. Шаг 4: Формирование ссылки для отправки в WhatsApp.

После каждого шага — проверяй результат в браузере и делай коммит в Git.


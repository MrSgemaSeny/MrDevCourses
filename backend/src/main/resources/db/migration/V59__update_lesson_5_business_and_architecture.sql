## 3. Архитектурная структура: Проектирование масштабируемости

Когда бизнес-цель ясна, инженер проектирует архитектурный скелет системы.

### 1. Карта страниц и экранов (Screen & Route Map)
С первого дня зафиксируй структуру маршрутов (URLs) и назначение каждого экрана:

- `/` — Публичный лендинг (Hero, оффер, витрина предзаказа, контакты).
- `/login` и `/register` — Экраны авторизации и регистрации.
- `/dashboard` — Личный кабинет клиента (активные заказы, статус готовности).
- `/admin` — Панель управления наставника/администратора (поток заказов, смена статусов, аналитика).

### 2. Ролевая модель и RBAC (Role-Based Access Control)
Самая частая ошибка новичков — делать одну общую страницу для всех. В реальном проекте доступ всегда строго разграничен по ролям:

| Роль | Права доступа (Permissions) | Доступные экраны |
|---|---|---|
| **GUEST (Гость)** | Просмотр лендинга, каталога, регистрация | `/`, `/login`, `/register` |
| **CUSTOMER (Клиент)** | Оформление заказов, просмотр своих статусов | `/`, `/dashboard/**`, `/profile` |
| **ADMIN / MANAGER (Администратор)** | Управление заказами, смена статусов, просмотр выручки | `/admin/**`, полный доступ к API |

### 3. Модель данных и ключевые сущности (Data Domain)
Определи ключевые сущности и связи между ними до создания таблиц в базе данных:

```
[User] (id, email, password_hash, role, created_at)
  │
  └── 1:N ──> [Order] (id, user_id, status, total_price, pickup_time, created_at)
                │
                └── 1:N ──> [OrderItem] (id, order_id, product_name, quantity, price)
```

Такая структура масштабируема: она легко расширяется добавлением новых полей без разрушения существующей базы.


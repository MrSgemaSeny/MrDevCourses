## 1. Два крыла IT-продукта: Бизнес и Архитектура

Профессиональный инженер отличается от обычного кодера тем, что видит систему целиком:

1. **Бизнес-структура (Цель и Ценность)**:
   - Какую конкретную боль человека решает продукт?
   - Что в итоге мы хотим увидеть как конечный результат (End Outcome)?
   - Без чего продукт не имеет смысла, а что является второстепенным шумом?

2. **Архитектурная структура (Фундамент и Масштабируемость)**:
   - Как спроектировать систему так, чтобы через полгода при росте базы не пришлось всё выбрасывать?
   - Сколько будет страниц и маршрутов?
   - Какие сущности данных и связи закладываются с первого дня?
   - Сколько ролей пользователей в системе и как устроена модель разграничения прав (RBAC)?

> [!IMPORTANT]
> Бизнес-структура без архитектуры приводит к техническому банкротству: проект тонет в багах при первом успехе. Архитектура без бизнес-цели приводит к созданию никому не нужных академических монолитов. Только их симбиоз даёт сильный продукт.


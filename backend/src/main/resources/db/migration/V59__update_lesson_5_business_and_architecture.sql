## 4. Инженерный мост: От User Story к техническому контракту

Каждое бизнес-требование трансформируется в конкретные технические компоненты:

> **User Story**: "Как спешащий клиент, я хочу нажать кнопку «Заберу через 10 минут», чтобы бариста сразу начал готовить мой заказ."

**Что это означает на уровне архитектуры**:
1. **Frontend**: Кнопка инициирует вызов `POST /api/v1/orders` с телом `{ productId: 1, pickupMinutes: 10 }`.
2. **API & Security**: Проверка JWT-токена в httpOnly cookie, валидация DTO (проверка, что `pickupMinutes > 0`).
3. **Database**: Атомарная транзакция в PostgreSQL: создание записи в `orders`, логирование в `audit_logs`.
4. **Real-time Event**: Отправка события вебхуком в Telegram-бот баристы с номером заказа и временем готовности.


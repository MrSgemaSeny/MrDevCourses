Помоги мне составить полный продуктово-архитектурный паспорт проекта:

1. БИЗНЕС-СТРУКТУРА:
   - Сформулируй 1 сильный Customer Problem Statement.
   - Опиши 1 конкретный портрет целевого пользователя (JTBD).
   - Разбей функционал по методу MoSCoW (не более 3 Must-Have фич).

2. АРХИТЕКТУРНАЯ СТРУКТУРА:
   - Составь карту экранов и маршрутов (Route Map).
   - Спроектируй ролевую модель RBAC (Гость, Клиент, Администратор).
   - Опиши базовую структуру таблиц базы данных и их связи (ERD).
   - Выдели 3 критические точки отказа при масштабировании до 10 000 пользователей и как их предотвратить.
```

Полученный структурированный бриф станет эталонным фундаментом для реализации лендинга и веб-приложения.


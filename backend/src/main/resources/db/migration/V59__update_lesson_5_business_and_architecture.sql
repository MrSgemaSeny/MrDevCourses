## 2. Бизнес-структура: Конечная цель и Customer Problem Statement

Прежде чем открыть редактор кода, необходимо зафиксировать конечную цель продукта.

### Формула Customer Problem Statement
Инженерный стандарт формулировки проблемы:

> **[Конкретная группа людей]** сталкивается с **[Конкретное неудобство / Боль]**, когда пытается **[Какое действие они совершают]**, из-за чего **[К какому плохому результату это приводит: потеря денег, времени, клиентов]**.

Сравним два подхода:
- **Слабо (мышление фичами)**: "Я хочу сделать красивый сайт для кофейни с каталогом и анимациями."
- **Сильно (мышление бизнес-результатом)**: "Студенты и сотрудники бизнес-центра тратят по 15 минут в очереди за кофе на 10-минутной перемене, из-за чего 40% клиентов уходят без покупки, а кофейня теряет до 300 000 тенге выручки в месяц."

### Безжалостный скоупинг MVP: Метод MoSCoW
Чтобы запустить первую версию за считанные дни, раздели все мыслимые фичи на 4 категории:

1. **Must Have (Обязательно для первой версии)**: Без этого сервис не решает проблему. Для кофейни: витрина 5 популярных напитков, выбор времени самовывоза, кнопка мгновенного предзаказа.
2. **Should Have (Важно, но терпит до релиза v1.1)**: Личный кабинет с историей заказов, фильтрация по объёму стаканчика.
3. **Could Have (Приятные дополнения v2.0)**: Накопительные баллы, промокоды, интеграция с картами лояльности.
4. **Won''t Have (Строго запрещено в MVP)**: Мобильное приложение в App Store, распознавание лиц постоянных клиентов, блокчейн-чаевые.


   - Укажи `base: ''./''` (относительный путь), чтобы все скомпилированные скрипты и стили корректно загружались из подпапки репозитория GitHub Pages без белого экрана.

2. В `package.json` в секцию `scripts` добавь команду пост-билда для обхода ошибки 404:
   - Обнови скрипт "build": `"tsc -b && vite build && cp dist/index.html dist/404.html"` (или кроссплатформенный аналог).
   - Если на Windows команда `cp` не поддерживается, создай легкий скрипт `scripts/copy-404.js` и вызови его через `node scripts/copy-404.js`.

## 1. В чём главная проблема SPA при деплое простыми словами

```
1. Обычный сайт:
   У тебя на сервере лежат файлы: `index.html`, `catalog.html`, `product.html`.
   Браузер просит `/product` → сервер находит файл `product.html` и отдаёт его. Всё работает.

2. React 19 SPA (Наш Маркетплейс):
   На сервере лежит всего ОДИН файл — `index.html`.
   Когда пользователь кликает на товар, адрес в браузере меняется на `/product/123`, но страница не перезагружается — React сам подменяет экран.

3. Ловушка F5 (Обновление страницы):
   Пользователь нажал F5 на странице `/product/123`.
   Браузер идёт на сервер GitHub и просит: "Дай мне файл /product/123".
   Сервер GitHub ищет такую папку на диске, не находит её и выдаёт уродливую ошибку: 404 Not Found!
```

> [!IMPORTANT]
> **Инженерный трюк:** Чтобы обойти эту проблему, мы научим сборщик Vite автоматически копировать `index.html` и сохранять его копию под именем `404.html`. Когда GitHub Pages не найдёт файл, он отдаст `404.html`, внутри которого загрузится наш React Router и мгновенно покажет нужный товар!


2. Установи необходимые права доступа: `pages: write`, `id-token: write`, `contents: read`.
3. Шаги сборки (Jobs):
   - Checkout репозитория (actions/checkout@v4).
   - Установка Node.js 20 (actions/setup-node@v4) с кешированием npm.
   - Установка зависимостей (`npm ci`).
   - Проверка типов и сборка (`npm run build`).
   - Загрузка собранных артефактов из папки `dist/` (actions/upload-pages-artifact@v3).
   - Публикация в GitHub Pages (actions/deploy-pages@v4).

Сделай YAML-файл чистым, лаконичным и 100% рабочим без устаревших версий экшенов.

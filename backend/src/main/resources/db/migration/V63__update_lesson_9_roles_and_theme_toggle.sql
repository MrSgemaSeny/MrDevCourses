## 3. Шаг 2: AI-Промпт для хранилища ролей и смены темы

Скопируй и отправь этот промпт в свой AI-ассистент:

```markdown
Ты — Senior React Engineer. Создай глобальные хранилища Zustand с автосохранением в LocalStorage:

1. Хранилище пользователя и ролей: `src/entities/user/model/userStore.ts`
   - Тип роли: `UserRole = ''BUYER'' | ''SELLER''`.
   - Состояние: `role` (по умолчанию ''BUYER''), `userName` (по умолчанию ''Алексей'').
   - Действия: `setRole(role)` и `toggleRole()`, которая переключает BUYER <-> SELLER.
   - Используй `persist` из `zustand/middleware` с ключом `marketplace-user`.

2. Хранилище темы оформления: `src/shared/model/themeStore.ts`
   - Тип темы: `ThemeMode = ''dark'' | ''light''`.
   - Состояние: `theme` (по умолчанию ''dark'').
   - Действие: `toggleTheme()`, которая переключает тему и автоматически вешает или снимает класс `dark` на теге `document.documentElement`.
   - Сохраняй выбор в LocalStorage через `persist` с ключом `marketplace-theme`.

3. Экспортируй хуки через Public API соответствующих слоёв (`entities/user/index.ts` и `shared/model/index.ts`).
```


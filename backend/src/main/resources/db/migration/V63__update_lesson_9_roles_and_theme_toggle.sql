## 4. Шаг 3: AI-Промпт для интерактивной корзины

Отправь следующий промпт для создания логики покупок:

```markdown
Создай фичу корзины покупок на Zustand в `src/features/cart/`:

1. `src/features/cart/model/cartStore.ts`:
   - Интерфейс `CartItem`: `product: Product`, `quantity: number`.
   - Состояние: массив `items`.
   - Действия:
     * `addItem(product)` — добавляет товар или увеличивает quantity, если товар уже в корзине.
     * `removeItem(productId)` — удаляет позицию.
     * `clearCart()` — очищает корзину.
     * `getTotalPrice()` — возвращает итоговую сумму в тенге.
     * `getTotalCount()` — возвращает общее число товаров.
   - Настрой персист в LocalStorage (ключ `marketplace-cart`).

2. `src/features/cart/ui/CartDrawer.tsx`:
   - Выезжающая справа панель (Drawer) со списком выбранных товаров.
   - Кнопка закрытия (крестик), список позиций с кнопками плюс/минус, итоговая сумма жирным шрифтом и кнопка "Оформить заказ в WhatsApp".
   - Стили: монохромная эстетика, поддержка темной/светлой темы (bg-card, border-border).

3. Экспортируй `useCartStore` и `CartDrawer` через `src/features/cart/index.ts`.
```


Раньше чтобы сделать сайт или приложение, нужно было несколько лет учиться программированию. Сейчас всё изменилось. И в этом уроке мы разберёмся — что именно изменилось, почему это важно, и как ты можешь этим воспользоваться уже сейчас.

## 1. Как раньше создавались продукты

Представь: у тебя есть идея. Допустим, ты хочешь сделать сайт для своего бизнеса или приложение для друзей. Что происходило раньше?

Либо ты шёл учиться программированию — минимум год-два, прежде чем мог сделать что-то реальное. Либо нанимал разработчика — дорого, долго, и ты всё равно не понимаешь что происходит.

Большинство идей так и умирали на этапе "хотелось бы, но не знаю как".

> [!NOTE]
> Это не потому что люди были ленивые или неспособные. Просто порог входа в разработку был очень высоким. Нужно было знать синтаксис языка, понимать архитектуру, уметь работать с инструментами — и всё это до того, как ты напишешь хоть одну рабочую строчку.

## 2. Что изменилось сейчас

В 2023–2024 году появились AI-ассистенты, которые умеют писать код. Claude, ChatGPT, Gemini — ты описываешь задачу человеческим языком, и получаешь рабочий результат.

Но самое важное — это не просто "AI пишет код вместо тебя". Это другой способ думать о создании продуктов.

Раньше путь был такой: сначала выучи инструменты, потом реализуй идею. Годы уходили на подготовку, и только потом — к делу.

Теперь путь другой. У тебя есть идея. Ты не можешь просто взять и реализовать её — технических знаний пока нет. Но ты можешь сделать вот что: составить подробный план того, что хочешь построить. Описать это AI. И дальше — AI становится твоей рабочей лошадкой. Ты направляешь, он строит. По ходу работы ты начинаешь понимать технологии — не в теории, а через реальные задачи. И в итоге собираешь продукт, который работает.

> [!IMPORTANT]
> Это и есть вайбкодинг. Не "AI делает всё за тебя". А ты — как архитектор и менеджер проекта, AI — как исполнитель. Ты думаешь, планируешь, принимаешь решения. AI реализует.

## 3. Почему это не "халтура"

Многие думают: если AI пишет код — значит я ничему не учусь. Это неправда.

Когда ты работаешь с AI над реальным проектом, ты неизбежно начинаешь разбираться в том, что происходит. Потому что AI иногда делает не то, что ты хотел — и тебе нужно понять почему. Потому что нужно объяснить задачу точно — а для этого нужно самому понимать что ты хочешь. Потому что ты смотришь на код, читаешь его, задаёшь вопросы — и знания накапливаются естественно.

Это как учиться вождению сразу на реальной машине, а не три года изучать теорию двигателя внутреннего сгорания перед тем как сесть за руль.

> [!TIP]
> Самый быстрый способ научиться — делать реальные проекты. Не учебные упражнения, а то что ты сам хочешь построить. На курсе мы именно так и работаем.

## 4. Что такое AI-ассистент и как с ним работать

AI-ассистент — это не поисковик. Ему не нужно вводить ключевые слова и потом читать 10 статей. Ты просто разговариваешь с ним как с человеком.

Можно сказать: "Я хочу сделать лендинг для кофейни. Не знаю с чего начать." И он объяснит с чего начать, предложит структуру, напишет первый вариант кода.

Можно сказать: "Вот мой код, он не работает. Что не так?" И он найдёт ошибку и объяснит почему она возникла.

Можно сказать: "Объясни мне что такое API простыми словами." И получишь объяснение без технического жаргона.

На курсе мы используем несколько инструментов. Claude — для сложных задач, архитектурных решений и объяснений. ChatGPT — для быстрых ответов. Cursor — это редактор кода со встроенным AI, который видит весь твой проект и помогает прямо внутри него. Gemini — там где нужна интеграция с Google.

> [!NOTE]
> Не нужно сразу разбираться во всех инструментах. На следующем уроке мы установим всё что нужно шаг за шагом.

## 5. Главное правило: ты должен понимать что происходит

AI уверенно пишет неправильный код. Это важно знать сразу.

Он может дать тебе код, который выглядит правильно, но не делает то что ты хотел. Или делает — но небезопасно. Или работает сейчас, но сломается при первой же нагрузке.

Поэтому твоя задача на этом курсе — не просто копировать что выдаёт AI. А понимать что происходит. Задавать вопросы. Разбираться в том, что ты строишь.

Хороший вопрос AI лучше чем слепо принятый ответ.

> [!WARNING]
> Самая частая ошибка новичков в вайбкодинге — принять первый ответ AI как финальный и не разобраться в нём. Так накапливается код, который никто не понимает. Включая тебя.


## 2. Разница между Git и GitHub: не путай тёплое с мягким

Многие новички думают, что Git и GitHub — это одно и то же. Это не так.

- **Git** — это локальная программа, которая живёт прямо на твоём компьютере. Она следит за каждым файлом в папке проекта, записывает каждую изменённую строчку и работает даже если полностью отключить интернет.
- **GitHub** — это облачный сервис (как Google Drive или Dropbox, но специально для кода). Ты загружаешь свои Git-снимки на GitHub, чтобы показать проект работодателям, работать в команде с другими разработчиками или бесплатно опубликовать свой сайт.

> [!IMPORTANT]
> Git работает локально у тебя на диске. GitHub — это облако в интернете. Сначала ты сохраняешь снимок локально в Git, и только потом отправляешь его в GitHub.

## 3. Три состояния твоих файлов в Git: как это устроено внутри

Чтобы уверенно пользоваться Git и не вводить команды вслепую, запомни простую схему из трёх пространств:

1. **Working Tree (Рабочая папка)**: Твои реальные файлы, которые ты открываешь в Cursor или VS Code. Здесь ты пишешь текст, меняешь стили, удаляешь картинки.
2. **Staging Area (Индекс / Зона подготовки)**: Это как корзина в супермаркете. Прежде чем пробить чек (сделать коммит), ты складываешь в корзину только те файлы, которые хочешь включить в следующий снимок. Команда `git add` перемещает файлы именно сюда.
3. **Repository (История коммитов)**: Запечатанный снимок, который навсегда сохраняется в скрытой папке `.git`. Команда `git commit` берёт всё из зоны подготовки и фиксирует снимок с твоим комментарием.

```
[Рабочая папка]  ──── git add ────>  [Зона подготовки]  ──── git commit ────>  [История Git]
```

## 4. Настройка за 2 минуты и первый локальный репозиторий

Перед тем как сделать первый снимок, нужно один раз представиться Git, чтобы в истории коммитов было видно, кто автор изменений:

```bash
git config --global user.name "Твоё Имя"
git config --global user.email "твой_email@gmail.com"
```

Теперь создадим новую папку для проекта и превратим её в Git-репозиторий:

```bash
# 1. Создаем папку и заходим в неё
mkdir my-first-landing
cd my-first-landing

# 2. Инициализируем Git (появится скрытая папка .git)
git init

# 3. Создаём простой файл index.html
echo "<h1>Мой первый проект на курсе Mr Developer</h1>" > index.html

# 4. Проверяем состояние
git status
```

Команда `git status` — твой главный компас. Она покажет красным цветом файл `index.html`. Это значит: Git видит файл, но пока не следит за ним.

Добавим его в зону подготовки и сохраним первый снимок:

```bash
# Добавляем все изменённые файлы в зону подготовки
git add .

# Фиксируем снимок с понятным комментарием
git commit -m "feat: initial project structure with index.html"
```

> [!TIP]
> Привыкай писать комментарии к коммитам на английском по стандарту Conventional Commits: `feat:` (когда добавил что-то новое), `fix:` (когда починил баг), `docs:` (когда обновил текст или инструкцию), `style:` (когда поправил отступы или цвет).

## 5. Подключение GitHub и первый git push

Теперь перенесём локальный репозиторий в облако GitHub:

1. Открой [github.com](https://github.com) и войди в свой аккаунт.
2. Справа сверху нажми на плюсик `+` -> **New repository**.
3. Назови репозиторий `my-first-landing`.
4. Сделай его **Public** (публичным).
5. **Важно**: не ставь галочки возле README, .gitignore или лицензии — репозиторий должен быть абсолютно пустым! Нажми зеленую кнопку **Create repository**.
6. GitHub покажет блок команд "push an existing repository from the command line". Скопируй их и выполни в своём терминале:

```bash
# Переименовываем главную ветку в современный стандарт main
git branch -M main

# Привязываем твой локальный репозиторий к репозиторию на GitHub
git remote add origin https://github.com/твой-логин/my-first-landing.git

# Отправляем весь проект и историю снимков в облако
git push -u origin main
```

Обнови страницу на GitHub — все твои файлы уже там!

## 6. Публикация сайта на GitHub Pages: получаем живую ссылку

GitHub умеет бесплатно запускать статические сайты прямо из репозитория:

1. В своём репозитории на GitHub нажми вкладку **Settings** (настройки с иконкой шестерёнки).
2. В левом меню найди раздел **Pages**.
3. В блоке **Branch** выбери ветку `main` и папку `/ (root)`.
4. Нажми кнопку **Save**.
5. Подожди 1-2 минуты и обнови страницу. Сверху появится зелёная плашка с живой ссылкой вида:
   `https://твой-логин.github.io/my-first-landing/`

Эту ссылку можно отправить друзьям или открыть с телефона — твой сайт официально опубликован в глобальном интернете!

> [!WARNING]
> Чтобы сайт отображался, главный файл обязан называться строго маленькими буквами: `index.html`. Если назвать его `Index.html` или `home.html`, GitHub Pages выдаст ошибку 404.

## 7. Файл .gitignore: как не отправить в интернет пароли и мусор

Не все файлы проекта должны попадать в репозиторий. Например:
- Папки с тяжелыми скачанными библиотеками (`node_modules`).
- Файлы с секретными ключами и паролями от базы данных (`.env`).
- Служебные файлы операционной системы (`.DS_Store` на Mac или `Thumbs.db` на Windows).

Для этого в корне проекта создаётся файл с точным именем `.gitignore`:

```
# Секретные ключи и переменные окружения
.env
*.local

# Зависимости
node_modules/
dist/

# Мусор операционных систем
.DS_Store
Thumbs.db
```

Всё, что перечислено в `.gitignore`, Git будет просто игнорировать.

## 8. Как работать с Git в паре с AI

Когда ты просишь Cursor или Claude внести изменения в код, держи в голове железное правило вайбкодинга:

**Сделай коммит ПЕРЕД тем, как просить AI сделать сложный рефакторинг.**

Если AI сделает что-то не то — ты просто нажмёшь в терминале:
```bash
git restore .
```
И весь проект мгновенно вернётся к состоянию последнего коммита. Это даёт колоссальную свободу экспериментов: ты больше никогда не боишься сломать код.


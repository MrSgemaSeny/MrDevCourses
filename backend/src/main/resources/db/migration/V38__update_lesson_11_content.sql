## 3. Разбор типичных архитектурных нарушений в FSD

Давай разберём две самые частые ошибки, которые находят во время ревью:

### Нарушение 1: Кросс-импорт между фичами (Cross-Feature Coupling)
Представь, что в фиче оформления заказа `features/checkout` разработчик написал:
```typescript
// ПЛОХО: фича лезет напрямую во внутренности соседней фичи
import { useCartStore } from ''@/features/cart/model/cartStore'';
```
Почему это плохо? Теперь фича `checkout` не может работать без фичи `cart`. Их невозможно переиспользовать по отдельности или протестировать в изоляции.
**Как исправить**: Состояние корзины выносится на уровень ниже — в `entities/cart`, либо передаётся сверху через композитный виджет.

### Нарушение 2: Забытые селекторы в Zustand
```typescript
// ПЛОХО: компонент будет заново перерисовываться при ЛЮБОМ изменении любого поля в сторе!
const store = useCartStore();

// ХОРОШО: атомарный селектор — ререндер сработает ТОЛЬКО при изменении количества
const totalCount = useCartStore((state) => state.items.length);
```


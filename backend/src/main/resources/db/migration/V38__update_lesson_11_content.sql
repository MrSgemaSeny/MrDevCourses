## 1. Зачем нужен Code Review и почему AI — твой лучший ментор

В реальных IT-компаниях ни одна строчка кода не попадает на рабочий сервер без проверки другим разработчиком (Code Review). Почему?
Потому что когда ты 4 часа подряд верстаешь одну и ту же форму, твой глаз "замыливается":
- Ты перестаёшь замечать потенциальные утечки памяти.
- Ты забываешь обработать граничные случаи (что если сервер вернул пустой массив или упал с ошибкой 500?).
- Ты нарушаешь правила FSD и связываешь компоненты намертво ради того, чтобы "просто быстрее заработало".

Claude идеально подходит на роль ревьюера: он не устаёт, помнит все спецификации TypeScript и видит архитектурные связи насквозь.

> [!NOTE]
> Главная цель Code Review — не указать на ошибки ради критики, а повысить читаемость, безопасность и масштабируемость проекта. Код пишется один раз, а читается и дорабатывается сотни раз.

## 2. Формулирование строгого системного промпта на Code Review

Если просто спросить AI: *"Посмотри мой компонент, всё ли там нормально?"*, ты получишь вежливый, но бесполезный ответ: *"Отличный код, всё выглядит современно!"*.

Чтобы получить настоящий глубокий аудит, инженер задаёт жесткие критерии и контекст:

```markdown
Ты — Senior Frontend Architect с 10-летним опытом в React 19, TypeScript и Feature-Sliced Design.

Критерии аудита:
1. Архитектура FSD:
   - Нет ли кросс-импортов между фичами одного слоя?
   - Нет ли импортов "снизу-вверх" (когда entity импортирует feature или widget)?
   - Экспортируются ли интерфейсы строго через фасад index.ts?
2. TypeScript:
   - Полное отсутствие типов any или неизвестных кастов (as unknown as T).

## 1. Что такое приёмочное тестирование (User Acceptance Testing)

В профессиональной разработке тестирование делится на несколько уровней:
- **Unit тесты**: Проверяют одну изолированную функцию (например, правильно ли считается сумма).
- **Integration тесты**: Проверяют, как два модуля работают вместе.
- **UAT (User Acceptance Testing / Приёмочное тестирование)**: Это проверка всего приложения целиком глазами реального пользователя. Мы не смотрим в код — мы открываем браузер и проходим сквозные пользовательские сценарии (User Journeys) от начала до конца.

